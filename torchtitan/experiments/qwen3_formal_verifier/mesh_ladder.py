"""Derive a ScoutBModel instance for a dp_shard x tp mesh of any degree.

Every invariant in this program has been checked on exactly one configuration:
four ranks, eight communicators, two non-trivial mesh axes. Whether they survive
past that was unanswerable while the instance was hand-written. This derives one.

The rule is read off the observed run rather than invented: the runtime creates
several communicators over the *same* axis, one per mesh name. In the observed
2x2 run that is `tp` over the tp axis, and `fsdp`, `batch` and `loss` over
dp_shard -- four names over two rank groupings, which is why eight communicators
appear over a mesh with only two non-trivial axes. Only `fsdp` carries the full
operation set; the rest are all_reduce.

The check that the rule is the right one: applying it at 2x2 reproduces the
shipped hand-written instance exactly, and TLC over the generated instance
explores the same state graph -- 133881 states generated, 38321 distinct -- as
the shipped one. A generator that agreed only on rank and communicator counts
would not establish that.

What this deliberately does not do is emit one communicator per mesh axis. That
would understate the set at 2x2, producing two where the runtime creates eight,
and it is the same eight-versus-four keying error ticket 11 exists to prevent.
"""

from __future__ import annotations

from dataclasses import dataclass

# The observed mesh names, and whether each carries the full operation set.
# Order is fixed so a generated module is byte-stable across runs.
TP_AXIS_MESH_NAMES: tuple[str, ...] = ("tp",)
DP_SHARD_AXIS_MESH_NAMES: tuple[str, ...] = ("fsdp", "batch", "loss")
FULL_OP_MESH_NAMES: frozenset[str] = frozenset({"fsdp"})


@dataclass(frozen=True)
class Communicator:
    """One communicator: a mesh name over one grouping of ranks."""

    name: str
    members: tuple[int, ...]
    all_operations: bool

    @property
    def ops_expression(self) -> str:
        """The TLA+ expression for this communicator's admissible operations."""
        return "Ops" if self.all_operations else '{"all_reduce"}'


@dataclass(frozen=True)
class MeshInstance:
    dp_shard: int
    tp: int
    ranks: tuple[int, ...]
    communicators: tuple[Communicator, ...]

    @property
    def tag(self) -> str:
        return f"D{self.dp_shard}T{self.tp}"


def derive_instance(dp_shard: int, tp: int) -> MeshInstance:
    """Derive the ranks and communicators for a dp_shard x tp mesh.

    Rank numbering follows the observed run: rank = dp_coordinate * tp +
    tp_coordinate, so a tp group is contiguous and a dp_shard group is strided.
    """
    if dp_shard < 1 or tp < 1:
        raise ValueError(f"mesh degrees must be positive: {dp_shard}x{tp}")

    tp_groups = [tuple(d * tp + t for t in range(tp)) for d in range(dp_shard)]
    dp_groups = [tuple(d * tp + t for d in range(dp_shard)) for t in range(tp)]

    communicators: list[Communicator] = []
    for name in TP_AXIS_MESH_NAMES:
        for group in tp_groups:
            communicators.append(
                Communicator(
                    f"{name}_{'_'.join(map(str, group))}",
                    group,
                    name in FULL_OP_MESH_NAMES,
                )
            )
    for name in DP_SHARD_AXIS_MESH_NAMES:
        for group in dp_groups:
            communicators.append(
                Communicator(
                    f"{name}_{'_'.join(map(str, group))}",
                    group,
                    name in FULL_OP_MESH_NAMES,
                )
            )
    return MeshInstance(
        dp_shard=dp_shard,
        tp=tp,
        ranks=tuple(range(dp_shard * tp)),
        communicators=tuple(communicators),
    )


def render_module(instance: MeshInstance) -> str:
    """Render a module that EXTENDS ScoutBModel and supplies the instance.

    Extending rather than editing is the point: the invariants are defined in
    ScoutBModel over its CONSTANTS, so binding different ones checks the same
    properties against a different mesh while the twenty shipped cfgs and the
    runner's awk scraper over the 2x2 definition names stay untouched.
    """
    tag = instance.tag
    ids = ", ".join(f'"{c.name}"' for c in instance.communicators)
    members = "\n".join(
        f'    [] c = "{c.name}" -> {{{", ".join(map(str, c.members))}}}'
        for c in instance.communicators
    )
    ops = "\n".join(
        f'    [] c = "{c.name}" -> {c.ops_expression}' for c in instance.communicators
    )
    return f"""---------------------------- MODULE ScoutBMeshLadder ----------------------------
(* Generated by mesh_ladder.py for a dp_shard={instance.dp_shard} x tp={instance.tp} mesh:
   {len(instance.ranks)} ranks, {len(instance.communicators)} communicators. Do not edit by hand. *)
EXTENDS ScoutBModel

Ranks{tag} == {{{", ".join(map(str, instance.ranks))}}}

CommIds{tag} == {{{ids}}}

CommMembers{tag} ==
  [c \\in CommIds{tag} |->
    CASE FALSE -> {{}}
{members}
    [] OTHER -> {{}}]

CommOps{tag} ==
  [c \\in CommIds{tag} |->
    CASE FALSE -> {{}}
{ops}
    [] OTHER -> {{}}]
================================================================================
"""


def render_cfg(instance: MeshInstance, *, max_issues: int) -> str:
    """Render the cfg binding this instance to ScoutBModel's safety invariants.

    max_issues is explicit because it dominates tractability far more than the
    mesh does: exhaustive checking reaches 8 ranks at 1 and stops at 4 ranks
    at 2.
    """
    tag = instance.tag
    return f"""\\* Generated by mesh_ladder.py. The shipped safety invariants, a derived mesh.
CONSTANT
  Ranks <- Ranks{tag}
  CommIds <- CommIds{tag}
  CommMembers <- CommMembers{tag}
  CommOps <- CommOps{tag}

CONSTANT
  MaxIssues = {max_issues}
  RequireMatchedIssueOrder = TRUE
  RequireUniformProgramOps = TRUE
  RequireUniformProgramComms = TRUE
  RequireStreamOrder = TRUE

SPECIFICATION Spec
INVARIANT
  TypeOK
  RendezvousOpAgreement
  RendezvousMembership
  CommFifo
  DeadlockFreedom
"""
